/**
 * Generates src/i18n/calendar-names.ts from this Node's ICU data.
 *
 *   npm run gen:calendar
 *
 * Runtime code never calls Intl's long date formats: their output differs between Node and
 * browsers (and between ICU versions), which breaks hydration. Instead the names are taken from
 * formatToParts once, with timeZone UTC, and committed so every change is reviewed in a diff.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { INTL_TAG, LOCALES, type Locale } from "../src/i18n/config";

type Names = {
  weekdays: string[];
  weekdaysShort: string[];
  months: string[];
  monthsStandalone: string[];
  monthsShort: string[];
};

function part(locale: Locale, opts: Intl.DateTimeFormatOptions, date: Date, type: Intl.DateTimeFormatPartTypes): string {
  const parts = new Intl.DateTimeFormat(INTL_TAG[locale], { timeZone: "UTC", ...opts }).formatToParts(date);
  const value = parts.find((p) => p.type === type)?.value;
  if (!value) throw new Error(`No ${type} part for ${locale} ${JSON.stringify(opts)}`);
  return value;
}

function namesFor(locale: Locale): Names {
  const weekdays: string[] = [];
  const weekdaysShort: string[] = [];
  // 1-7 Feb 2026 covers every weekday; index by getUTCDay() (0 = Sunday).
  for (let i = 1; i <= 7; i++) {
    const d = new Date(Date.UTC(2026, 1, i));
    // Ask in a "weekday + day + month" context: some locales abbreviate differently there (de "Di.").
    weekdays[d.getUTCDay()] = part(locale, { weekday: "long", day: "numeric", month: "long" }, d, "weekday");
    weekdaysShort[d.getUTCDay()] = part(locale, { weekday: "short", day: "numeric", month: "short" }, d, "weekday");
  }
  const months: string[] = [];
  const monthsStandalone: string[] = [];
  const monthsShort: string[] = [];
  for (let m = 0; m < 12; m++) {
    const d = new Date(Date.UTC(2026, m, 13));
    // After a day number: the genitive where the language has one (pl "13 października").
    months.push(part(locale, { day: "numeric", month: "long" }, d, "month"));
    // On its own, as in "październik 2026".
    monthsStandalone.push(part(locale, { month: "long" }, d, "month"));
    // pt-PT formats day + short month as "13/10"; fall back to the stand-alone abbreviation.
    const short = part(locale, { day: "numeric", month: "short" }, d, "month");
    monthsShort.push(/^\d+$/.test(short) ? part(locale, { month: "short" }, d, "month") : short);
  }
  return { weekdays, weekdaysShort, months, monthsStandalone, monthsShort, ...OVERRIDES[locale] };
}

/**
 * Deliberate departures from CLDR. en-GB abbreviates September as "Sept", the only 4-letter
 * month: "Sep" keeps short labels 3 letters wide in calendar columns, as before the i18n core.
 */
const OVERRIDES: Partial<Record<Locale, Partial<Names>>> = {
  en: { monthsShort: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"] },
};

const data = Object.fromEntries(LOCALES.map((l) => [l, namesFor(l)])) as Record<Locale, Names>;

const body = LOCALES.map((l) => {
  const n = data[l];
  const row = (k: keyof Names) => `    ${k}: [${n[k].map((s) => JSON.stringify(s)).join(", ")}],`;
  return [`  ${l}: {`, row("weekdays"), row("weekdaysShort"), row("months"), row("monthsStandalone"), row("monthsShort"), "  },"].join(
    "\n",
  );
}).join("\n");

const out = `/**
 * GENERATED by scripts/gen-calendar-names.ts (npm run gen:calendar). Do not edit by hand:
 * fix the generator or date-patterns.ts instead, and review the diff.
 * Source: Node ${process.versions.node}, ICU ${process.versions.icu}, CLDR ${process.versions.cldr ?? "?"}.
 *
 * weekdays / weekdaysShort: index 0 = Sunday (Date#getUTCDay).
 * months: the form used after a day number (Polish genitive "października").
 * monthsStandalone: the form used alone or with a year (Polish nominative "październik").
 */
import type { Locale } from "./config";

export type CalendarNames = {
  weekdays: readonly string[];
  weekdaysShort: readonly string[];
  months: readonly string[];
  monthsStandalone: readonly string[];
  monthsShort: readonly string[];
};

export const CALENDAR_NAMES: Record<Locale, CalendarNames> = {
${body}
};
`;

const target = path.resolve(__dirname, "../src/i18n/calendar-names.ts");
writeFileSync(target, out);
console.log(`✓ wrote ${path.relative(process.cwd(), target)}`);
